"""WatermarkForge command-line interface.

Usage (run from the repo root; the package is importable as ``watermarkforge``):

    python cli.py demo      # run the full benchmark, write benchmark.json + summary report
    python cli.py verify    # run benchmark + acceptance gates, exit non-zero if any gate fails
    python cli.py watermark <scheme> <length> [seed]
                            # watermark a random sequence, print detection result

Author: 晨星
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from core.config import Config
from core.seed import set_all
from core.types import TokenSeq
from data.generator import KeyedHasher, SyntheticGenerator
from detect.detectors import get_detector
from pipeline.pipeline import WatermarkPipeline
from watermark.schemes import get_scheme

ROOT = Path(__file__).resolve().parent
REPORT = ROOT / "benchmark_summary.md"


def _cmd_demo(args: argparse.Namespace) -> int:
    cfg = Config()
    pipe = WatermarkPipeline(cfg)
    rep = pipe.run()
    gates = pipe.gates(rep)
    (ROOT / "benchmark.json").write_text(json.dumps(rep, indent=2), encoding="utf-8")
    _write_report(rep, gates)
    n_pass = sum(g["pass"] for g in gates)
    print(f"benchmark.json written ({len(rep['records'])} records, {rep['elapsed_sec']}s)")
    print(f"gates: {n_pass}/{len(gates)} passed")
    return 0


def _cmd_verify(args: argparse.Namespace) -> int:
    cfg = Config()
    pipe = WatermarkPipeline(cfg)
    rep = pipe.run()
    gates = pipe.gates(rep)
    (ROOT / "benchmark.json").write_text(json.dumps(rep, indent=2), encoding="utf-8")
    _write_report(rep, gates)
    n_pass = sum(g["pass"] for g in gates)
    print(f"gates: {n_pass}/{len(gates)} passed")
    for g in gates:
        mark = "PASS" if g["pass"] else "FAIL"
        print(f"  [{mark}] {g['code']}  {g['desc']}")
    return 0 if n_pass == len(gates) else 1


def _cmd_watermark(args: argparse.Namespace) -> int:
    cfg = Config()
    hasher = KeyedHasher(cfg)
    gen = SyntheticGenerator(cfg, hasher)
    rng = set_all(args.seed)
    strengths = {s: 1.0 for s in ("kgw", "gumbel", "wmfuse")}
    if cfg.equal_distortion:
        from eval.benchmark import calibrated_strengths
        strengths = calibrated_strengths(cfg, hasher)
    for s, v in strengths.items():
        gen.set_strength(s, v)
    xs = gen.watermark(args.scheme, 1, args.length, rng)
    seq = TokenSeq(tokens=[int(t) for t in xs[0]])
    scheme = get_scheme(args.scheme, cfg, hasher, gen)
    res = scheme.watermark(seq, rng)
    det = get_detector(args.scheme)
    dr = det.detect(seq, hasher, cfg)
    print(json.dumps({
        "scheme": args.scheme, "length": args.length, "seed": args.seed,
        "strength": round(res.strength, 4), "distortion_kl": round(res.kl, 4),
        "tokens": res.tokens,
        "detect_score": round(dr.score, 4), "is_watermarked": dr.is_watermarked,
    }, ensure_ascii=False, indent=2))
    return 0


def _write_report(rep: dict, gates: list) -> None:
    head = rep["headline"]
    cfg = rep["config"]
    lines = [
        "# WatermarkForge Benchmark Report",
        "",
        f"- generated by `python cli.py demo` (elapsed {rep['elapsed_sec']}s)",
        f"- equal-distortion budget target_kl = {cfg['target_kl']} nats/token",
        f"- measured distortion: kgw={cfg['kmgw']:.4f} gumbel={cfg['kgumbel']:.4f} "
        f"wmfuse={cfg['kwmfuse']:.4f}",
        f"- calibrated strengths: kgw={cfg['strength_kgw']:.4f} "
        f"gumbel={cfg['strength_gumbel']:.4f} wmfuse={cfg['strength_wmfuse']:.4f}",
        f"- determinism: max_abs_diff = {rep['determinism']['max_abs_diff']} "
        f"(bit_identical={rep['determinism']['bit_identical']})",
        "",
        "## Acceptance gates",
        "",
        "| code | desc | pass | detail |",
        "|------|------|------|--------|",
    ]
    for g in gates:
        detail = json.dumps(g["detail"], ensure_ascii=False)
        if len(detail) > 120:
            detail = detail[:117] + "..."
        lines.append(f"| {g['code']} | {g['desc']} | {'✅' if g['pass'] else '❌'} | {detail} |")
    lines += ["", "## Clean detectability (TPR @ 1% FPR)", ""]
    lines.append("| length | kgw | gumbel | wmfuse |")
    lines.append("|--------|-----|--------|--------|")
    for L in cfg["lengths"]:
        row = head["clean_tpr"][f"L{L}"]
        lines.append(f"| L{L} | {row['kgw']:.3f} | {row['gumbel']:.3f} | {row['wmfuse']:.3f} |")
    lines += ["", "## Robustness vs best baseline (TPR @ 1% FPR, delta) — flagship = gumbel (+ multi-scale union)", ""]
    lines.append("| cell | kgw | gumbel | wmfuse | baseline_best | delta |")
    lines.append("|------|-----|--------|--------|--------------|-------|")
    for key, cell in head["per_cell"].items():
        lines.append(f"| {key} | {cell['kgw_tpr']:.2f} | {cell['gumbel_tpr']:.2f} | "
                     f"{cell['wmfuse_tpr']:.2f} | {cell['baseline_best_tpr']:.2f} | "
                     f"{cell['delta_vs_baseline']:+.2f} |")
    lines.append("")
    REPORT.write_text("\n".join(lines), encoding="utf-8")
    print(f"report written -> {REPORT}")


def main() -> int:
    p = argparse.ArgumentParser(prog="watermarkforge", description="WatermarkForge CLI (author: 晨星)")
    sub = p.add_subparsers(dest="cmd", required=True)
    sub.add_parser("demo", help="run benchmark, write benchmark.json + summary")
    sub.add_parser("verify", help="run benchmark + acceptance gates")
    wm = sub.add_parser("watermark", help="watermark one sequence and detect it")
    wm.add_argument("scheme", choices=["kgw", "gumbel", "wmfuse"])
    wm.add_argument("length", type=int, nargs="?", default=50)
    wm.add_argument("seed", type=int, nargs="?", default=7)
    args = p.parse_args()
    if args.cmd == "demo":
        return _cmd_demo(args)
    if args.cmd == "verify":
        return _cmd_verify(args)
    if args.cmd == "watermark":
        return _cmd_watermark(args)
    return 2


if __name__ == "__main__":
    sys.exit(main())
